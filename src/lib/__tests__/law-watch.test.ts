import { describe, expect, it } from "vitest";
import { isFederalAct, matchRateKeys } from "../law-watch";

const t = (title: string) => matchRateKeys({ title });

describe("отбор актов", () => {
  it("ловит настоящее изменение постановления об утильсборе", () => {
    const r = t(
      'Постановление Правительства Российской Федерации от 01.11.2025 № 1713 ' +
        '"О внесении изменений в постановление Правительства Российской Федерации ' +
        'от 26 декабря 2013 г. № 1291"'
    );
    expect(r.rateKeys).toContain("recycling_ice");
    expect(r.rateKeys).toContain("recycling_ev");
  });

  it("ловит поправки в Налоговый кодекс, хотя слова «акциз» в заголовке нет", () => {
    // Ставки акцизов правили именно так: ФЗ № 425-ФЗ.
    const r = t(
      'Федеральный закон от 28.11.2025 № 425-ФЗ "О внесении изменений в часть ' +
        'вторую Налогового кодекса Российской Федерации"'
    );
    expect(r.rateKeys).toContain("excise");
  });

  it("не срабатывает на региональный приказ с номером 342", () => {
    // Реальный ложный положительный из первого прогона.
    const r = t(
      'Приказ Министерства социальной защиты Тульской области от 08.09.2026 ' +
        '№ 342-осн "О формировании и ведении реестра поставщиков социальных услуг"'
    );
    expect(r.rateKeys).toEqual([]);
  });

  it("не срабатывает на памятник культуры «Склады Акцизного управления»", () => {
    // Тоже реальный ложный положительный: одного слова «акциз» мало.
    const r = t(
      'Приказ Инспекции по охране объектов культурного наследия Костромской ' +
        'области от 07.09.2026 № 67-НПА "Об утверждении предмета охраны объекта ' +
        'культурного наследия "Склады Акцизного управления, кон. XIX в."'
    );
    expect(r.rateKeys).toEqual([]);
  });

  it("обычный федеральный акт мимо нашей темы не трогает ставки", () => {
    const r = t(
      'Постановление Правительства Российской Федерации от 12.09.2026 № 1164 ' +
        '"О внесении изменений в постановление Правительства Российской Федерации ' +
        'от 30 октября 2025 г. № 1687"'
    );
    expect(r.rateKeys).toEqual([]);
  });
});

describe("федеральность", () => {
  it.each([
    ["Постановление Правительства Российской Федерации от 01.11.2025 № 1713", true],
    ["Федеральный закон от 28.11.2025 № 425-ФЗ", true],
    ["Приказ Министерства социальной защиты Тульской области № 342-осн", false],
    ["Постановление Правительства Республики Крым № 1291", false],
  ])("%s -> %s", (title, expected) => {
    expect(isFederalAct(title)).toBe(expected);
  });
});
